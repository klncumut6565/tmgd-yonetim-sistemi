-- dönerse o UN numarası TMGD tarafından ayrıca incelenmelidir)
SELECT k.atik_kodu, k.atik_adi, k.un_number
FROM public.atik_kodlari_katalogu k
WHERE NOT EXISTS (
  SELECT 1 FROM public.adr_un_numbers a WHERE a.un_number = k.un_number
)
ORDER BY k.un_number, k.atik_kodu;

